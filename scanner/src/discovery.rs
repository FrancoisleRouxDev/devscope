// discovery.rs - finds project folders under a workspace root and measures them.
// A folder is a project if it contains a marker file (.git, package.json,
// Cargo.toml, ...). For each project we compute total size, how much of it is
// rebuildable "junk" (node_modules, target, venv, ...) and the last activity.

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::UNIX_EPOCH;

use rayon::prelude::*;
use walkdir::WalkDir;

use crate::types::ProjectInfo;

const MARKERS: &[(&str, &str)] = &[
    (".git", "git"),
    ("package.json", "node"),
    ("Cargo.toml", "rust"),
    ("pyproject.toml", "python"),
    ("requirements.txt", "python"),
    ("go.mod", "go"),
    ("pom.xml", "java"),
    ("build.gradle", "java"),
];

/// Folders that can be regenerated by a build or install step.
pub const JUNK_DIRS: &[&str] = &[
    "node_modules", "target", "venv", ".venv", "__pycache__", "dist", "build", ".next", ".svelte-kit",
];

/// Find projects under `root`, descending at most `max_depth` levels.
pub fn discover(root: &Path, max_depth: usize) -> Vec<ProjectInfo> {
    let mut found = Vec::new();
    find(root, 0, max_depth, &mut found);
    // Measuring is the slow part (walks every file), so do it in parallel.
    let mut projects: Vec<ProjectInfo> = found.par_iter().map(|(p, k)| measure(p, k)).collect();
    projects.sort_by(|a, b| b.size_bytes.cmp(&a.size_bytes));
    projects
}

fn find(dir: &Path, depth: usize, max_depth: usize, out: &mut Vec<(PathBuf, Vec<String>)>) {
    let Ok(entries) = fs::read_dir(dir) else { return };
    let entries: Vec<_> = entries.filter_map(Result::ok).collect();

    let kinds: BTreeSet<String> = entries
        .iter()
        .filter_map(|e| {
            let name = e.file_name();
            let name = name.to_str()?;
            MARKERS.iter().find(|(m, _)| *m == name).map(|(_, k)| k.to_string())
        })
        .collect();

    if !kinds.is_empty() {
        out.push((dir.to_path_buf(), kinds.into_iter().collect()));
        return; // do not look for projects nested inside a project
    }
    if depth >= max_depth {
        return;
    }
    for e in entries {
        let name = e.file_name();
        let Some(name) = name.to_str() else { continue };
        let is_dir = e.file_type().map_or(false, |t| t.is_dir()); // symlinks are not followed
        if is_dir && !name.starts_with('.') && !JUNK_DIRS.contains(&name) {
            find(&e.path(), depth + 1, max_depth, out);
        }
    }
}

fn measure(path: &Path, kinds: &[String]) -> ProjectInfo {
    let mut info = ProjectInfo {
        path: path.to_string_lossy().into_owned(),
        name: path.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default(),
        kinds: kinds.to_vec(),
        ..Default::default()
    };
    let mut junk: BTreeSet<String> = BTreeSet::new();

    for entry in WalkDir::new(path).follow_links(false).into_iter().filter_map(Result::ok) {
        if !entry.file_type().is_file() {
            continue;
        }
        let Ok(meta) = entry.metadata() else { continue };
        let len = meta.len();
        info.size_bytes += len;

        let rel = entry.path().strip_prefix(path).unwrap_or(entry.path());
        let top = rel.components().next().and_then(|c| c.as_os_str().to_str()).unwrap_or("");

        if JUNK_DIRS.contains(&top) && rel.components().count() > 1 {
            info.junk_bytes += len;
            junk.insert(top.to_string());
        } else if top != ".git" {
            let secs = meta
                .modified()
                .ok()
                .and_then(|t| t.duration_since(UNIX_EPOCH).ok())
                .map_or(0, |d| d.as_secs() as i64);
            info.last_modified = info.last_modified.max(secs);
        }
    }
    info.junk_dirs = junk.into_iter().collect();
    info
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn finds_projects_and_junk() {
        let root = std::env::temp_dir().join(format!("devscope_disc_{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        fs::create_dir_all(root.join("a/node_modules/dep")).unwrap();
        fs::create_dir_all(root.join("group/b")).unwrap();
        fs::write(root.join("a/package.json"), "{}").unwrap();
        fs::write(root.join("a/node_modules/dep/index.js"), "x".repeat(100)).unwrap();
        fs::write(root.join("group/b/Cargo.toml"), "").unwrap();

        let found = discover(&root, 4);
        assert_eq!(found.len(), 2);
        let a = found.iter().find(|p| p.name == "a").unwrap();
        assert_eq!(a.junk_bytes, 100);
        assert_eq!(a.junk_dirs, vec!["node_modules"]);
        assert!(found.iter().any(|p| p.name == "b" && p.kinds == vec!["rust"]));
        let _ = fs::remove_dir_all(&root);
    }
}
